create table public.grievances (
  id bigint generated by default as identity primary key,
  ticket_id text unique not null,
  name text,
  phone text,
  email text,
  address text,
  latitude double precision,
  longitude double precision,
  photo_data text,
  complaint text not null,
  category text,
  priority text,
  department text,
  status text default 'Pending',
  eta date,
  created_at timestamptz default now()
);

alter table public.grievances add column if not exists address text;
alter table public.grievances add column if not exists photo_data text;
alter table public.grievances add column if not exists latitude double precision;
alter table public.grievances add column if not exists longitude double precision;

alter table public.grievances enable row level security;

create policy "Backend service can manage grievances"
on public.grievances
for all
to service_role
using (true)
with check (true);

-- ================= ALERTS TABLE =================
create table if not exists public.alerts (
  id bigint generated by default as identity primary key,
  ticket_id text,
  title text not null,
  message text not null,
  priority text default 'Normal',
  department text,
  category text,
  status text default 'Unread',
  created_at timestamptz default now()
);

alter table public.alerts enable row level security;

create policy "Allow all users to read alerts"
on public.alerts for select using (true);

create policy "Allow all users to insert alerts"
on public.alerts for insert with check (true);

-- ================= ESCALATION COLUMNS FOR COMPLAINTS =================
alter table public.complaints add column if not exists deadline_at timestamptz;
alter table public.complaints add column if not exists escalated boolean default false;
alter table public.complaints add column if not exists escalated_to text;
alter table public.complaints add column if not exists escalated_at timestamptz;
alter table public.complaints add column if not exists initial_department text;

-- Policy to update complaints on escalation
do $$
begin
  if not exists (
    select 1 from pg_policies where tablename = 'complaints' and policyname = 'Allow update complaints'
  ) then
    create policy "Allow update complaints" on public.complaints for update using (true);
  end if;
end $$;
