create table public.grievances (
  id bigint generated by default as identity primary key,
  ticket_id text unique not null,
  name text,
  phone text,
  email text,
  address text,
  latitude double precision,
  longitude double precision,
  photo_data text,
  complaint text not null,
  category text,
  priority text,
  department text,
  status text default 'Pending',
  eta date,
  created_at timestamptz default now()
);

alter table public.grievances add column if not exists address text;
alter table public.grievances add column if not exists photo_data text;
alter table public.grievances add column if not exists latitude double precision;
alter table public.grievances add column if not exists longitude double precision;

alter table public.grievances enable row level security;

create policy "Backend service can manage grievances"
on public.grievances
for all
to service_role
using (true)
with check (true);